"""Word timings for the two soundtracks.  Run: npm run transcribe  (uv, Python 3.11)

Reads public/audio/dialogue.m4a and poem.m4a (taken without re-encoding from
audio.mp4 and the reference video), transcribes them with Whisper (small.en,
on the CPU) and writes src/generated/speech.ts: every word with its start and
end in seconds from the start of its clip, and its loudness: RMS per
1/ENVELOPE_RATE seconds, 0..1 (1 = the clip's loudest), so visuals can follow
the voice while staying a pure function of time. The captions refer to the
words by index.
"""
import json
from pathlib import Path

import numpy as np
from faster_whisper import WhisperModel, decode_audio

ROOT = Path(__file__).resolve().parent.parent
CLIPS = {"dialogue": ROOT / "public/audio/dialogue.m4a", "poem": ROOT / "public/audio/poem.m4a"}
OUT = ROOT / "src/generated/speech.ts"
ENVELOPE_RATE = 20


def main() -> None:
    model = WhisperModel("small.en", device="cpu", compute_type="int8")
    data = {}
    for name, path in CLIPS.items():
        segments, info = model.transcribe(str(path), word_timestamps=True, beam_size=5)
        words = [
            {"text": w.word.strip(), "start": round(w.start, 3), "end": round(w.end, 3)}
            for seg in segments
            for w in seg.words
        ]
        pcm = decode_audio(str(path), sampling_rate=16000)
        hop = 16000 // ENVELOPE_RATE
        rms = np.sqrt([np.mean(pcm[i : i + hop] ** 2) for i in range(0, len(pcm) - hop + 1, hop)])
        envelope = [round(float(v), 2) for v in rms / max(rms.max(), 1e-9)]
        data[name] = {"duration": round(info.duration, 3), "envelopeRate": ENVELOPE_RATE, "envelope": envelope, "words": words}
        print(name, len(words), "words:", " ".join(f"{i}:{w['text']}" for i, w in enumerate(words)))
    OUT.write_text(
        "// Generated by scripts/transcribe.py (npm run transcribe). Do not edit by hand.\n"
        "// Seconds from the start of each clip in public/audio.\n"
        f"export const SPEECH = {json.dumps(data, indent=1)} as const;\n"
    )
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
